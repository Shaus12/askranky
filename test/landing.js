// First-touch landing buckets on GET /api/internal/status -> funnel.landing. Aggregate buckets only.
import assert from 'node:assert/strict';
import fs from 'node:fs';
import { useTempData } from './helpers.js';
const TD = useTempData('landing');
for (const k of ['PRELAUNCH', 'PAYMENTS_PROVIDER', 'SCAN_MODE', 'EMAIL_MODE', 'FUNNEL_FLUSH_MS', 'OWNER_EMAILS', 'COMP_ACCOUNTS']) delete process.env[k];
const TOKEN = 'status-token-0123456789-abcdefghij';
Object.assign(process.env, { DISABLE_IP_LIMIT: '1', STATUS_TOKEN: TOKEN, STATUS_FAIL_MAX: '1000', SCAN_RATE_MAX: '1000', LAND_RATE_MAX: '100000', OWNER_EMAILS: 'boss@t.test' });
const { pathBucket } = await import('../web/lib/path-bucket.js');
const { default: app } = await import('../server.js');
const { getDb } = await import('../src/store.js');
const { flushVisits, resetFunnelMemory } = await import('../src/funnel.js');
const { cleanBucket } = await import('../src/landing.js');
const srv = app.listen(0); await new Promise(r => srv.once('listening', r)); const B = 'http://127.0.0.1:' + srv.address().port;
let n = 0; const ok = m => { n++; console.log('  ✓', m); };
const FB = 'Mozilla/5.0 (iPhone; CPU iPhone OS 17_0 like Mac OS X) AppleWebKit/605.1.15 (KHTML, like Gecko) Mobile/15E148 [FBAN/FBIOS;FBAV/450.0.0.0;FBBV/1;FBDV/iPhone15,2;FBMD/iPhone;FBSN/iOS;FBSV/17.0;FBSS/3;FBOP/5]';
const UA = 'Mozilla/5.0 (X11; Linux x86_64) Chrome/130 Safari/537.36';
const land = (body, ua = UA, h = {}) => fetch(B + '/api/v/land', { method: 'POST', headers: { 'content-type': 'application/json', 'user-agent': ua, ...h }, body: JSON.stringify(body) });
const post = (p, body, ua = UA) => fetch(B + p, { method: 'POST', headers: { 'content-type': 'application/json', 'user-agent': ua }, body: JSON.stringify(body) });
const status = async () => (await (await fetch(B + '/api/internal/status', { headers: { 'x-status-token': TOKEN } })).json());
const bucket = (block, path) => block.find(r => r.path === path);
try {
  for (const [p, b] of [['/he', 'he'], ['/he/', 'he'], ['/HE', 'he'], ['/en', 'en'], ['/en/', 'en'], ['/he/blog', 'blog'], ['/en/blog/some-post', 'blog'], ['/blog', 'blog'], ['/he/r/reportid-SHOULD-NOT-LEAK', 'report'], ['/r/abc?x=1', 'report'], ['/en/agencies', 'agencies'], ['/agencies', 'agencies'], ['/he/pricing', 'other'], ['/he/scan', 'other'], ['/he/legal/privacy', 'other'], ['', 'other']]) assert.equal(pathBucket(p), b, p);
  assert.equal(cleanBucket('blog'), 'blog');
  for (const bad of ['/he/r/SECRET', 'https://askranky.com/he/r/SECRET?q=1', 'report?id=1', 'He', 'facebook', '', null]) assert.equal(cleanBucket(bad), null, String(bad));
  ok('path buckets: home, blog, report and agencies; raw URLs and report ids are not a bucket');

  resetFunnelMemory();
  assert.equal((await land({ path: 'he', utm_ref: 'facebook.com' }, FB)).status, 204);
  assert.equal((await land({ path: 'he' }, FB)).status, 204);
  assert.equal((await land({ path: 'blog' }, UA)).status, 204);
  assert.equal((await land({ path: 'en' })).status, 204);
  assert.equal((await land({ path: 'report' }, FB)).status, 204);
  assert.equal((await land({ path: 'agencies' })).status, 204);
  assert.equal((await land({ path: 'other' })).status, 204);
  await land({ path: '/he/r/SECRET-REPORT-ID' }, FB);
  await land({ path: 'https://askranky.com/en?utm_source=x' }, FB);
  await land({ path: 'he' }, 'facebookexternalhit/1.1');
  await land({ path: 'he' }, FB, { 'x-ranky-monitor': '1' });
  await land({ path: 'he' }, '');
  let s = await status();
  const today = s.funnel.landing.today;
  assert.deepEqual(today.map(r => r.path), ['he', 'en', 'blog', 'report', 'agencies', 'other']);
  assert.equal(bucket(today, 'he').visits, 2);
  assert.equal(bucket(today, 'he').visitors, 1, 'same browser twice is one visitor');
  assert.equal(bucket(today, 'blog').visits, 1);
  assert.equal(bucket(today, 'en').visits, 1);
  assert.equal(bucket(today, 'report').visits, 1);
  assert.equal(bucket(today, 'agencies').visits, 1);
  assert.equal(bucket(today, 'other').visits, 1);
  assert.equal(today.reduce((a, r) => a + r.visits, 0), 7, 'raw paths, bots, empty UA and X-Ranky-Monitor are not counted');
  assert.equal(bucket(s.funnel.landing.last7Days, 'he').visits, 2);
  assert.equal(bucket(s.funnel.landing.sinceTracking, 'report').visits, 1);
  assert.equal(s.funnel.sources.last7Days.find(r => r.source === 'ref:facebook.com').visits, 1, 'source counts still work beside the path bucket');
  const leaked = JSON.stringify(s.funnel.landing);
  assert.ok(!leaked.includes('SECRET') && !leaked.includes('http') && !leaked.includes('?') && !/reportid/i.test(leaked));
  ok('landing beacon: six buckets, FB in-app counted, monitors and raw paths dropped, no URL or report id in the payload');

  const scan = await post('/api/scan', { name: 'Landing Cafe', city: 'Haifa', lang: 'he', path: 'blog', utm_ref: 'facebook.com' }, FB);
  assert.equal(scan.status, 200);
  const { reportId } = await scan.json();
  const db = getDb();
  const stored = db.scans[reportId];
  assert.equal(stored.land, 'blog');
  assert.equal(db.accounts[stored.accountId].guest, true);
  assert.equal(db.accounts[stored.accountId].land, 'blog');
  s = await status();
  assert.equal(bucket(s.funnel.landing.today, 'blog').scanStarted, 1);
  assert.equal(bucket(s.funnel.landing.today, 'blog').scanDone, 1);
  assert.equal(bucket(s.funnel.landing.today, 'blog').signup, 0, 'a guest scan is not a signup');
  assert.equal(s.signups.total, 0, 'guest account is excluded from status signups');
  assert.equal(s.funnel.today.signup, 0);
  ok('guest scan stores the bucket on the scan and the account; signup stays 0');

  assert.equal((await post('/api/report/' + reportId + '/unlock', { email: 'land1@t.test', lang: 'he' }, FB)).status, 200);
  const acc = Object.values(getDb().accounts).find(a => a.email === 'land1@t.test');
  assert.equal(acc.land, 'blog');
  s = await status();
  assert.equal(bucket(s.funnel.landing.today, 'blog').emailUnlocked, 1);
  assert.equal(bucket(s.funnel.landing.today, 'blog').signup, 1);
  assert.equal(s.signups.total, 1);
  assert.equal(s.funnel.today.signup, 1);
  const pub = await (await fetch(B + '/api/report/' + reportId)).json();
  assert.equal(pub.scan.land, undefined, 'bucket is not part of the public report');
  assert.ok(!JSON.stringify(pub).includes('"land"'));
  ok('unlock copies the bucket onto the new account and counts one signup; the public report does not include it');

  const raw = await post('/api/scan', { name: 'No Bucket', city: 'Haifa', lang: 'he', path: '/he/r/SECRET-REPORT-ID' });
  assert.equal(raw.status, 200);
  const rawId = (await raw.json()).reportId;
  assert.equal(getDb().scans[rawId].land, undefined);
  assert.ok(!JSON.stringify(getDb().scans[rawId]).includes('SECRET'));
  const own = await post('/api/scan', { name: 'Owner Cafe', city: 'Haifa', email: 'boss@t.test', category: 'Cafe', path: 'he' });
  assert.equal(own.status, 200);
  s = await status();
  assert.equal(bucket(s.funnel.landing.today, 'he').scanDone, 0);
  assert.equal(bucket(s.funnel.landing.today, 'he').signup, 0);
  assert.equal(s.signups.total, 1, 'owner account is not a signup');
  ok('a raw path is dropped; an owner scan does not enter the landing buckets or signups');

  assert.equal(flushVisits() >= 0, true);
  const ev = getDb().events.filter(e => e.type === 'funnel.path_visits');
  assert.ok(ev.length >= 1);
  for (const e of ev) assert.deepEqual(Object.keys(e).sort(), ['at', 'day', 'n', 'p', 'type', 'u']);
  assert.ok(ev.every(e => ['he', 'en', 'blog', 'report', 'agencies', 'other'].includes(e.p)));
  s = await status();
  assert.equal(bucket(s.funnel.landing.sinceTracking, 'blog').visits, 1);
  assert.ok(s.funnel.landing.trackingSince);
  assert.match(s.funnel.landing.note, /Historical/);
  assert.equal((await fetch(B + '/api/internal/status')).status, 404);
  ok('buckets flush as aggregate {day,p,n,u} only; status stays token-protected; historical note is present');

  const old = new Date(Date.now() - 400 * 864e5).toISOString();
  getDb().accounts.old1 = { id: 'old1', email: 'old1@t.test', plan: 'free', createdAt: old, usage: {}, land: 'he' };
  getDb().scans.oldscan = { id: 'oldscan', accountId: 'old1', at: old, land: 'he' };
  s = await status();
  assert.equal(bucket(s.funnel.landing.sinceTracking, 'he').signup, 0);
  assert.equal(bucket(s.funnel.landing.sinceTracking, 'he').scanDone, 0);
  ok('rows from before path tracking are not backfilled into the buckets');

  const client = fs.readFileSync('web/lib/utm.ts', 'utf8');
  assert.match(client, /path: pathBucket\(window\.location\.pathname\)/);
  assert.match(client, /\/api\/v\/land/);
  assert.ok(!/document\.cookie|localStorage/.test(client));
  console.log(`landing: ${n} passed`);
} finally { srv.close(); TD.done(); }
